def version_key(v):
    """'1.10.0' > '1.9.3' のように数で比べるための形。読めない部分は 0。"""
    out = []
    for part in str(v or "").split("."):
        try:
            out.append(int(part))
        except ValueError:
            out.append(0)
    return tuple(out + [0] * (3 - len(out)))
